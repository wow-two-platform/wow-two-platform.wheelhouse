using Wheelhouse.Application.Abstractions;
using Wheelhouse.Application.Deployments.Settings.Commands;
using Wheelhouse.Application.Deployments.Settings.Services;
using Wheelhouse.Application.SecretsVault.Models;
using WoW.Two.Sdk.Beta.Be.Foundation.Errors;
using WoW.Two.Sdk.Beta.Be.Mediator.Cqrs;
using WoW.Two.Sdk.Beta.Be.Mediator.Result;

namespace Wheelhouse.Application.Deployments.Settings.CommandHandlers;

/// <summary>Handles <see cref="SecretRegenerateCommand"/>: reads the key's declaration from the release (else the one the
/// target runs), refuses a key Wheelhouse does not generate or the owner linked to another product's key, then makes the
/// value as a deploy would — random bytes here, or the command from the declaring service's image in that release — and
/// writes it as a new version.</summary>
public sealed class SecretRegenerateCommandHandler(
    ITargetsRepository targets,
    IProductsRepository products,
    DeploymentSettingsService settings,
    GeneratedSettingsService generated,
    ISettingLinksRepository links)
    : ICommandHandler<SecretRegenerateCommand, AppResult<SecretWritten>>
{
    /// <inheritdoc />
    public async ValueTask<AppResult<SecretWritten>> HandleAsync(SecretRegenerateCommand request, CancellationToken cancellationToken)
    {
        var target = await targets.GetBySlugAsync(request.Target, cancellationToken);
        var product = target is null ? null : await products.GetByIdAsync(target.ProductId, cancellationToken);
        if (target is null || product is null)
            return AppResult<SecretWritten>.Fail(AppErrorFactory.NotFound($"Target '{request.Target}' was not found."));

        var declarations = await settings.DeclarationsAsync(target, product, request.Release, cancellationToken);
        if (declarations.GetValueOrDefault(request.Key) is not { Generate: not null } declaration)
            return AppResult<SecretWritten>.Fail(AppErrorFactory.Conflict(
                request.Key + " is not generated by Wheelhouse here; write a new value instead."));
        if ((await links.GetAsync(product.Id, target.Environment, cancellationToken)).FirstOrDefault(link => link.Key == request.Key) is { } linked)
            return AppResult<SecretWritten>.Fail(AppErrorFactory.Conflict(request.Key + " is linked to "
                + ((await targets.GetByIdAsync(linked.SourceTargetId, cancellationToken))?.Slug ?? "another target") + " " + linked.SourceKey
                + "; regenerate the source, or unlink it first."));
        var release = request.Release ?? (await settings.RunningAsync(target.Slug, cancellationToken))?.Bundle;
        var written = await generated.RegenerateAsync(target, product, declaration, release, request.Note, request.Actor, cancellationToken);
        if (written is AppResult<SecretWritten>.Success { Data: var version })
            request.Outcome.Detail = "v" + version.Version + " generated (" + declaration.Generate!.Kind + ")";
        return written;
    }
}
