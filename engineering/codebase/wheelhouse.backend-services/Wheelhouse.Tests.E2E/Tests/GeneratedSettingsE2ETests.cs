    /// <summary>A succeeded deploy of release v1.0.0 to foreverpin-dev, so its declarations are the running release's.</summary>
    private static object Succeeded() => new
    {
        id = Guid.NewGuid().ToString(), targetId = "foreverpin-dev", environment = "dev", bundleId = "foreverpin-gh-1",
        release = "v1.0.0", actor = "test-admin", status = "succeeded", submittedAt = "2026-10-19T10:00:00+00:00",
    };

    /// <summary>A key pair and its self-signed certificate ending at <see cref="NotAfter"/>, as a key command prints it.</summary>
    private static string Certificate()
    {
        using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        using var certificate = new CertificateRequest("CN=signing", key, HashAlgorithmName.SHA256)
            .CreateSelfSigned(NotAfter.AddYears(-1), NotAfter);
        return key.ExportPkcs8PrivateKeyPem() + "\n" + certificate.ExportCertificatePem();
    }

    /// <summary>Asserts that no reply the console reads carries any of <paramref name="texts"/>.</summary>
    private async Task ShouldNotShow(params string[] texts)
    {
        foreach (var path in new[]
                 {
                     "/api/audit", Settings, Settings + "?release=foreverpin-gh-1", "/api/deployments/history?notApplied=true",
                     "/api/deployments/targets/foreverpin-dev/secrets/" + ClientSecret + "/versions",
                     "/api/deployments/targets/foreverpin-dev/secrets/" + Signing + "/versions",
                 })
        {
            // A secret this test never held has no history to read.
            var response = await AdminClient.GetAsync(path);
            var body = await response.Content.ReadAsStringAsync();
            foreach (var text in texts)
                body.Should().NotContain(text, path);
        }
    }

    private Task<HttpResponseMessage> Deploy() =>
        Owner("deploy").PostAsJsonAsync(Deploys, new { target = "foreverpin-dev", release = "foreverpin-gh-1" });

    private static string Regenerate(string key) => "/api/deployments/targets/foreverpin-dev/secrets/" + key + "/regenerate";

    private static JsonElement Key(JsonElement plan, string service, string key) =>
        plan.GetProperty("services").EnumerateArray().Single(item => item.GetProperty("name").GetString() == service)
            .GetProperty("keys").EnumerateArray().Single(item => item.GetProperty("key").GetString() == key);

    private static string? Source(JsonElement plan, string service, string key) => Key(plan, service, key).GetProperty("source").GetString();

    private HttpClient Owner(string action)
    {
        var client = AdminClient;
        client.DefaultRequestHeaders.Add("X-Wheelhouse-Action", action);
        return client;
    }

    private async Task<JsonElement> DataAsync(string path)
    {
        var response = await AdminClient.GetAsync(path);
        response.StatusCode.Should().Be(HttpStatusCode.OK, await response.Content.ReadAsStringAsync());
        return (await response.Content.ReadFromJsonAsync<JsonElement>()).GetProperty("data");
    }
}
