namespace Wheelhouse.Tests.E2E.Tests;

/// <summary>
/// E2E for generated and linked setting keys (descriptor § Generated and linked keys): a deploy generates each missing
/// <c>generate</c> key before it starts — random bytes in process, a command through the runner's <c>generate-setting</c>
/// (faked here) — stores it as a vault version (a certificate's end date as its expiry), audits the keys and the deploy
/// and never replaces a stored value; a failing command stops the deploy with the runner's error line; Regenerate writes a
/// new version the next deploy applies; a linked key (<c>from</c>) is read-only, takes its source's secrecy and counts
/// as set while its source is. No generated value appears in a reply, the audit or a history.
/// </summary>
[Collection(WheelhouseCollection.Name)]
public sealed class GeneratedSettingsE2ETests(WheelhouseAppFixture fixture) : WheelhouseE2EBase(fixture)
{
    private const string Signing = "Identity:Server:Keys:Signing:0";
    private const string ClientSecret = "Identity:Server:Clients:0:ClientSecret";
    private const string LinkedSecret = "Auth:ClientSecret";
    private const string Deploys = "/api/deployments";
    private const string Settings = "/api/deployments/targets/foreverpin-dev/settings";

    private static readonly DateTimeOffset NotAfter = new(2027, 3, 4, 5, 6, 7, TimeSpan.Zero);

    [Fact]
    public async Task Deploy_ShouldGenerateEachMissingKeyBeforeItStarts_AndNeverReplaceAStoredOne()
    {
        DeclareIdentity();
        var pem = Certificate();
        Fixture.Deployments.Generated[Signing] = AppResult<GeneratedSettingValue>.Ok(new GeneratedSettingValue(pem + "\n"));

        var plan = await DataAsync(Settings + "?release=foreverpin-gh-1");
        (Source(plan, "identity", Signing), Source(plan, "identity", ClientSecret)).Should().Be(("generate", "generate"));
        plan.GetProperty("missing").GetInt32().Should().Be(0, "a key Wheelhouse generates never waits on the owner");
        var random = Key(plan, "identity", ClientSecret).GetProperty("generate");
        (random.GetProperty("random").GetInt32(), random.GetProperty("encoding").GetString()).Should().Be((32, "base64url"));
        Key(plan, "identity", Signing).GetProperty("generate").GetProperty("command").EnumerateArray().Select(part => part.GetString())
            .Should().Equal("dotnet", "Identity.Api.dll", "keys", "generate", "--role", "signing");

        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        Fixture.Deployments.Generations.Should().Equal([("foreverpin-dev", "foreverpin-gh-1", "identity", Signing)]);
        var values = Fixture.Deployments.LastSettings!.Value.GetProperty("values");
        var secret = values.GetProperty(ClientSecret).GetString()!;
        secret.Should().MatchRegex("^[A-Za-z0-9_-]{43}$", "32 random bytes as unpadded base64url");
        values.GetProperty(Signing).GetString().Should().Be(pem, "the command's output, without its trailing newline");
        values.TryGetProperty(LinkedSecret, out _).Should().BeFalse("a linked key renders its source's value on the target");

        var after = await DataAsync(Settings + "?release=foreverpin-gh-1");
        (Source(after, "identity", Signing), Source(after, "identity", ClientSecret)).Should().Be(("vault", "vault"));
        var vault = Key(after, "identity", Signing).GetProperty("vault");
        (vault.GetProperty("version").GetInt32(), vault.GetProperty("expiresAt").GetDateTimeOffset()).Should().Be((1, NotAfter),
            "a certificate's end date is its version's expiry");
        var history = await DataAsync("/api/deployments/targets/foreverpin-dev/secrets/" + Signing + "/versions");
        history.GetProperty("versions")[0].GetProperty("origin").GetString().Should().Be("generated by the deploy of v1.0.0 (command)");

        var audit = (await AdminClient.AuditItemsAsync()).EnumerateArray()
            .Single(entry => entry.GetProperty("action").GetString() == "settings.generate");
        (audit.GetProperty("subject").GetString(), audit.GetProperty("outcome").GetString(), audit.GetProperty("detail").GetString())
            .Should().Be(("foreverpin-dev", "succeeded",
                ClientSecret + " v1 (random 32 bytes base64url), " + Signing + " v1 (command); deploy of v1.0.0"));

        // The next deploy finds both stored: nothing runs again, nothing is replaced.
        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        Fixture.Deployments.Generations.Should().HaveCount(1);
        Fixture.Deployments.LastSettings!.Value.GetProperty("values").GetProperty(ClientSecret).GetString().Should().Be(secret);
        Key(await DataAsync(Settings + "?release=foreverpin-gh-1"), "identity", ClientSecret).GetProperty("vault").GetProperty("version")
            .GetInt32().Should().Be(1);
        await ShouldNotShow(secret, "PRIVATE KEY", "BEGIN CERTIFICATE");
    }

    [Fact]
    public async Task Deploy_ShouldGenerateAgain_AKeyTheOwnerRemoved_AndRenderTheNewVersion()
    {
        DeclareIdentity();
        Fixture.Deployments.Generated[Signing] = AppResult<GeneratedSettingValue>.Ok(new GeneratedSettingValue(Certificate()));
        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        var first = Fixture.Deployments.LastSettings!.Value.GetProperty("values").GetProperty(ClientSecret).GetString()!;
        (await Owner("settings").PutAsJsonAsync(Settings,
                new { values = new[] { new { key = ClientSecret, value = "", secret = true, remove = true } } }))
            .StatusCode.Should().Be(HttpStatusCode.OK);

        // The deploy's own reads ran before the generation wrote; the render still reads the new version.
        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        var again = Fixture.Deployments.LastSettings!.Value.GetProperty("values").GetProperty(ClientSecret).GetString();
        again.Should().MatchRegex("^[A-Za-z0-9_-]{43}$").And.NotBe(first);
        Key(await DataAsync(Settings + "?release=foreverpin-gh-1"), "identity", ClientSecret).GetProperty("vault").GetProperty("version")
            .GetInt32().Should().Be(2, "the removed secret's versions stay; the new value is the next one");
    }

    [Fact]
    public async Task Deploy_ShouldStopBeforeTheRunnerHearsOfIt_WhenAGenerateCommandFails()
    {
        DeclareIdentity();
        Fixture.Deployments.Generated[Signing] = AppResult<GeneratedSettingValue>.Fail(
            AppErrorFactory.ExternalUnavailable("keys generate exited 2: unknown role"));

        var refused = await Deploy();
        refused.StatusCode.Should().Be(HttpStatusCode.Conflict);
        (await refused.Content.ReadAsStringAsync()).Should().Contain("Generating " + Signing + " failed: keys generate exited 2: unknown role");
        Fixture.Deployments.Starts.Should().BeEmpty("no rollout step ran");
        var intent = (await DataAsync("/api/deployments/history?notApplied=true")).GetProperty("items").EnumerateArray()
            .Should().ContainSingle().Subject;
        intent.GetProperty("cause").GetProperty("message").GetString().Should().StartWith("Generating " + Signing + " failed");
        var audit = (await AdminClient.AuditItemsAsync()).EnumerateArray()
            .Single(entry => entry.GetProperty("action").GetString() == "settings.generate");
        (audit.GetProperty("outcome").GetString(), audit.GetProperty("detail").GetString()).Should().Be(("failed",
            ClientSecret + " v1 (random 32 bytes base64url), " + Signing + " failed; deploy of v1.0.0"));
        audit.GetProperty("reason").GetString().Should().Contain("unknown role");

        // The key made before the failure stays; the retry runs only the failed command.
        Fixture.Deployments.Generated[Signing] = AppResult<GeneratedSettingValue>.Ok(new GeneratedSettingValue(Certificate()));
        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        Fixture.Deployments.Generations.Select(call => call.Key).Should().Equal(Signing, Signing);
        Key(await DataAsync(Settings + "?release=foreverpin-gh-1"), "identity", ClientSecret).GetProperty("vault").GetProperty("version")
            .GetInt32().Should().Be(1);
    }

    [Fact]
    public async Task Regenerate_ShouldWriteANewVersion_ThatTheNextDeployApplies()
    {
        DeclareIdentity();
        Fixture.Deployments.History.Add(Succeeded());
        Fixture.Deployments.Generated[Signing] = AppResult<GeneratedSettingValue>.Ok(new GeneratedSettingValue(Certificate()));
        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        var first = Fixture.Deployments.LastSettings!.Value.GetProperty("values").GetProperty(ClientSecret).GetString()!;

        (await AdminClient.PostAsJsonAsync(Regenerate(ClientSecret), new { })).StatusCode
            .Should().Be(HttpStatusCode.BadRequest, "a regeneration carries its action header");
        var response = await Owner("settings").PostAsJsonAsync(Regenerate(ClientSecret), new { note = "rotated after the audit" });
        var reply = await response.Content.ReadAsStringAsync();
        response.StatusCode.Should().Be(HttpStatusCode.OK, reply);
        var written = (await response.Content.ReadFromJsonAsync<JsonElement>()).GetProperty("data");
        (written.GetProperty("key").GetString(), written.GetProperty("version").GetInt32()).Should().Be((ClientSecret, 2));
        reply.Should().NotContain(first);

        var plan = await DataAsync(Settings);
        plan.GetProperty("unapplied").EnumerateArray().Select(key => key.GetString()).Should().Contain(ClientSecret,
            "the next deploy applies it");
        var versions = (await DataAsync("/api/deployments/targets/foreverpin-dev/secrets/" + ClientSecret + "/versions"))
            .GetProperty("versions");
        (versions[0].GetProperty("note").GetString(), versions[0].GetProperty("origin").GetString())
            .Should().Be(("rotated after the audit", "regenerated (random 32 bytes base64url)"));
        (await AdminClient.AuditItemsAsync()).EnumerateArray()
            .Single(entry => entry.GetProperty("action").GetString() == "settings.secret.regenerate")
            .GetProperty("detail").GetString().Should().Be(ClientSecret + " v2 generated (random 32 bytes base64url)");

        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        var second = Fixture.Deployments.LastSettings!.Value.GetProperty("values").GetProperty(ClientSecret).GetString()!;
        second.Should().MatchRegex("^[A-Za-z0-9_-]{43}$").And.NotBe(first);

        // A command key regenerates from the image of the release the target runs.
        (await Owner("settings").PostAsync(Regenerate(Signing), null)).StatusCode.Should().Be(HttpStatusCode.OK);
        Fixture.Deployments.Generations.Last().Should().Be(("foreverpin-dev", "foreverpin-gh-1", "identity", Signing));

        var plain = await Owner("settings").PostAsJsonAsync(Regenerate("Desk:Theme"), new { });
        plain.StatusCode.Should().Be(HttpStatusCode.Conflict);
        (await plain.Content.ReadAsStringAsync()).Should().Contain("Desk:Theme is not generated by Wheelhouse");
        await ShouldNotShow(first, second);
    }

    [Fact]
    public async Task LinkedKey_ShouldBeReadOnly_TakeItsSourcesSecrecy_AndCountAsSetWhileItsSourceIs()
    {
        DeclareLinked();
        var plan = await DataAsync(Settings + "?release=foreverpin-gh-1");
        var linked = Key(plan, "desk", LinkedSecret);
        (linked.GetProperty("source").GetString(), linked.GetProperty("from").GetString(), linked.GetProperty("secret").GetBoolean())
            .Should().Be(("missing", ClientSecret, true), "its source is still missing");
        (Source(plan, "desk", "Auth:Issuer"), Key(plan, "desk", "Auth:Issuer").GetProperty("from").GetString())
            .Should().Be(("linked", "Sites:identity:Url"), "a derived source is always set");
        var email = Key(plan, "desk", "Desk:SupportEmail");
        (email.GetProperty("source").GetString(), email.GetProperty("value").GetString(), email.GetProperty("type").GetString())
            .Should().Be(("linked", "help@example.com", "email"), "a plain source's value and type show through");

        var saved = await Owner("settings").PutAsJsonAsync(Settings,
            new { values = new[] { new { key = LinkedSecret, value = "typed-by-hand", secret = true } } });
        saved.StatusCode.Should().Be(HttpStatusCode.BadRequest);
        (await saved.Content.ReadAsStringAsync()).Should().Contain(LinkedSecret + " takes its value from " + ClientSecret);
        (await AdminClient.GetAsync("/api/deployments/targets/foreverpin-dev/secrets/" + LinkedSecret + "/versions"))
            .StatusCode.Should().Be(HttpStatusCode.NotFound, "nothing was written");

        var waiting = await Deploy();
        waiting.StatusCode.Should().Be(HttpStatusCode.Conflict);
        (await waiting.Content.ReadAsStringAsync()).Should().Contain(
            "Fill in the required settings first: desk: " + LinkedSecret + " (from " + ClientSecret + "); identity: " + ClientSecret + ".");

        (await Owner("settings").PutAsJsonAsync(Settings,
                new { values = new[] { new { key = ClientSecret, value = "SOURCE_SECRET_9c1", secret = true } } }))
            .StatusCode.Should().Be(HttpStatusCode.OK);
        var ready = await DataAsync(Settings + "?release=foreverpin-gh-1");
        (Source(ready, "desk", LinkedSecret), ready.GetProperty("missing").GetInt32()).Should().Be(("linked", 0));
        Key(ready, "desk", LinkedSecret).GetProperty("value").ValueKind.Should().Be(JsonValueKind.Null, "a secret source's value never shows");

        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        var values = Fixture.Deployments.LastSettings!.Value.GetProperty("values");
        values.GetProperty(ClientSecret).GetString().Should().Be("SOURCE_SECRET_9c1");
        values.TryGetProperty(LinkedSecret, out _).Should().BeFalse("the target renders the source's value into it");

        (await AdminClient.GetAsync("/api/deployments/targets/foreverpin-dev/check?release=foreverpin-gh-1"))
            .StatusCode.Should().Be(HttpStatusCode.OK);
        Fixture.Deployments.LastCheckKeys.Should().Contain([ClientSecret, LinkedSecret, "Auth:Issuer"]);
        await ShouldNotShow("SOURCE_SECRET_9c1");
    }

    [Fact]
    public async Task KeyOneServiceOwnsAndAnotherLinks_ShouldStaySettable_AndReachTheDeploy()
    {
        const string BaseUrl = "Files:BaseUrl";
        const string Resource = "Identity:Server:Resources:2:Uri";
        Fixture.Deployments.History.Add(Succeeded());
        // Blog links the key, Brand owns it, Marketing links it again: the owner's declaration wins in either order.
        Fixture.Deployments.Declarations = new
        {
            targetId = "foreverpin-dev", release = "v1.0.0", product = "foreverpin", environment = "dev",
            services = new object[]
            {
                new { name = "blog", hostFile = false, keys = new object[] { new { key = BaseUrl, required = true, secret = false, from = Resource } } },
                new { name = "brand", hostFile = false, keys = new object[] { new { key = BaseUrl, required = true, secret = false, type = "url" } } },
                new { name = "identity", hostFile = false, keys = new object[] { new { key = Resource, required = true, secret = false, type = "url" } } },
                new { name = "marketing", hostFile = false, keys = new object[] { new { key = BaseUrl, required = true, secret = false, from = Resource } } },
            },
        };

        (await Owner("settings").PutAsJsonAsync(Settings, new
            {
                values = new[]
                {
                    new { key = BaseUrl, value = "https://files.example.test/" },
                    new { key = Resource, value = "https://files.example.test/" },
                },
            }))
            .StatusCode.Should().Be(HttpStatusCode.OK, "Brand declares the key as its own, so its value is the owner's to set");

        (await Deploy()).StatusCode.Should().Be(HttpStatusCode.Accepted);
        Fixture.Deployments.LastSettings!.Value.GetProperty("values").GetProperty(BaseUrl).GetString()
            .Should().Be("https://files.example.test/", "Brand renders the stored value; Blog and Marketing render their source's");
    }

    /// <summary>Declares an Identity service whose signing key a command makes and whose client secret is random, and a
    /// desk service that links to the client secret and keeps a plain setting of its own.</summary>
    private void DeclareIdentity() =>
        Fixture.Deployments.Declarations = new
        {
            targetId = "foreverpin-dev", release = "v1.0.0", product = "foreverpin", environment = "dev",
            services = new object[]
            {
                new
                {
                    name = "desk", hostFile = false,
                    keys = new object[]
                    {
                        new { key = LinkedSecret, required = true, secret = false, from = ClientSecret },
                        new { key = "Desk:Theme", required = false, secret = false, type = "text", @default = "light" },
                    },
                },
                new
                {
                    name = "identity", hostFile = false,
                    keys = new object[]
                    {
                        new { key = ClientSecret, required = true, secret = true, generate = new { random = 32, encoding = "base64url" } },
                        new
                        {
                            key = Signing, required = true, secret = true,
                            generate = new { command = new[] { "dotnet", "Identity.Api.dll", "keys", "generate", "--role", "signing" }, timeoutSeconds = 60 },
                        },
                        new { key = "Identity:Server:Issuer", required = true, secret = false, from = "Sites:identity:Url" },
                    },
                },
            },
        };

    /// <summary>Declares a desk service whose keys link to an Identity secret, a derived site URL and a plain default.</summary>
    private void DeclareLinked()
    {
        Fixture.Deployments.History.Add(Succeeded());
        Fixture.Deployments.Declarations = new
        {
            targetId = "foreverpin-dev", release = "v1.0.0", product = "foreverpin", environment = "dev",
            services = new object[]
            {
                new
                {
                    name = "desk", hostFile = false,
                    keys = new object[]
                    {
